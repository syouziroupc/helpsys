    public static void Validate()
    {
        if (Lessons.Count < 25) throw new InvalidOperationException("基礎課程の単元数が不足しています。");
        var ids = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        foreach (var lesson in Lessons)
        {
            if (!ids.Add(lesson.Id)) throw new InvalidOperationException($"重複する単元ID: {lesson.Id}");
            if (lesson.Objectives.Length < 2) throw new InvalidOperationException($"学習目標不足: {lesson.Id}");
            if (lesson.PracticeSteps.Length < 2) throw new InvalidOperationException($"練習項目不足: {lesson.Id}");
            if (lesson.Quiz.Length < 2) throw new InvalidOperationException($"確認問題不足: {lesson.Id}");
            foreach (var quiz in lesson.Quiz)
            {
                if (quiz.Choices.Length < 2 || quiz.CorrectIndex < 0 || quiz.CorrectIndex >= quiz.Choices.Length)
                    throw new InvalidOperationException($"確認問題が不正です: {lesson.Id}");
            }
        }
        if (Glossary.Count < 30) throw new InvalidOperationException("用語集の項目数が不足しています。");
    }

